"""CSV-only split audit. Does not open video or npy. Does not edit splits.json."""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
ML_ROOT = REPO_ROOT / "ml"
if str(ML_ROOT) not in sys.path:
    sys.path.insert(0, str(ML_ROOT))

from qawam_ml.filters import apply_filter  # noqa: E402
from qawam_ml.rehab24 import load_splits, person_ids_for_split  # noqa: E402

SPLIT_ORDER = ("train", "validation", "test")
QUALITY_SPLITS = ("train", "validation")
MIN_CLASS_REPS = 10


def _rel(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return resolved.as_posix()


def _markdown_table(headers: list[str], rows: list[list[object]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    sep = "| " + " | ".join("---" for _ in headers) + " |"
    body = ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join([head, sep, *body])


def _records(df) -> list[dict]:
    return df.to_dict(orient="records")


def build_report(csv_path: Path, splits_path: Path) -> str:
    import pandas as pd

    splits = load_splits(splits_path)
    df = pd.read_csv(csv_path, sep=";")
    frames: dict[str, object] = {}
    lines: list[str] = [
        "# REHAB24-6 split audit",
        "",
        "Generated by `ml/eval/audit_splits.py`. Reads only `Segmentation.csv` "
        "(semicolon) and `ml/splits.json`. No video, no `.npy`, `ml/splits.json` "
        "not modified. Test-split **counts** below are CSV metadata for "
        "`person_id` in the frozen test list; this script does not call "
        "`load_repetitions('test')` and does not write `logs/test_access.jsonl`.",
        "",
        f"- CSV: `{_rel(csv_path)}`",
        f"- Splits: `{_rel(splits_path)}`",
        f"- Rows in CSV: {len(df)}",
        "",
        "## Persons per split",
        "",
    ]

    person_rows: list[list[object]] = []
    for name in SPLIT_ORDER:
        allowed = person_ids_for_split(splits, name)  # type: ignore[arg-type]
        subset = df[df["person_id"].isin(allowed)]
        frames[name] = subset
        persons = sorted(int(p) for p in subset["person_id"].unique())
        person_rows.append(
            [name, len(persons), ", ".join(str(p) for p in persons), len(subset)]
        )
    lines.append(
        _markdown_table(
            ["split", "n_persons", "person_id", "n_repetitions"],
            person_rows,
        )
    )

    lines.extend(["", "## Repetitions per split × exercise × correctness", ""])
    corr_rows: list[list[object]] = []
    warnings: list[str] = []
    for name in SPLIT_ORDER:
        subset = frames[name]
        grouped = (
            subset.groupby(["exercise_id", "correctness"], dropna=False)
            .size()
            .reset_index(name="n")
        )
        for exercise_id in range(1, 7):
            for correctness in (0, 1):
                n = int(
                    grouped.loc[
                        (grouped["exercise_id"] == exercise_id)
                        & (grouped["correctness"] == correctness),
                        "n",
                    ].sum()
                )
                corr_rows.append([name, exercise_id, correctness, n])
                if n < MIN_CLASS_REPS:
                    warnings.append(
                        f"split={name} exercise_id={exercise_id} "
                        f"correctness={correctness} n={n} (<{MIN_CLASS_REPS})"
                    )
    lines.append(
        _markdown_table(
            ["split", "exercise_id", "correctness", "n_repetitions"],
            corr_rows,
        )
    )

    lines.extend(["", "## Persons per exercise per split", ""])
    person_ex_rows: list[list[object]] = []
    for name in SPLIT_ORDER:
        subset = frames[name]
        for exercise_id, group in subset.groupby("exercise_id"):
            persons = sorted(int(p) for p in group["person_id"].unique())
            person_ex_rows.append(
                [
                    name,
                    int(exercise_id),
                    len(persons),
                    ", ".join(str(p) for p in persons),
                    len(group),
                ]
            )
    lines.append(
        _markdown_table(
            ["split", "exercise_id", "n_persons", "person_id", "n_repetitions"],
            person_ex_rows,
        )
    )

    lines.extend(["", "## cam17_orientation counts per exercise × split", ""])
    orient_rows: list[list[object]] = []
    for name in SPLIT_ORDER:
        subset = frames[name]
        counts = Counter(
            (int(ex), str(view))
            for ex, view in zip(
                subset["exercise_id"],
                subset["cam17_orientation"],
                strict=True,
            )
        )
        for (exercise_id, view), n in sorted(counts.items()):
            orient_rows.append([name, exercise_id, view, n])
    lines.append(
        _markdown_table(
            ["split", "exercise_id", "cam17_orientation", "n_repetitions"],
            orient_rows,
        )
    )

    lines.extend(
        [
            "",
            "## Quality-filter repetition counts (train and validation only)",
            "",
            "Filters from `qawam_ml.filters`. Test split is omitted here.",
            "",
        ]
    )
    quality_rows: list[list[object]] = []
    for name in QUALITY_SPLITS:
        records = _records(frames[name])
        for filter_name in ("gt_quality", "label_quality"):
            for cam in (17, 18):
                kept = apply_filter(records, filter_name, cam)
                quality_rows.append([name, filter_name, cam, len(kept), len(records)])
    lines.append(
        _markdown_table(
            ["split", "filter", "cam", "n_kept", "n_in_split"],
            quality_rows,
        )
    )

    lines.extend(["", "## Warnings (class with fewer than 10 repetitions)", ""])
    if warnings:
        lines.extend(f"- {item}" for item in warnings)
    else:
        lines.append("- none")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Audit frozen REHAB24-6 subject splits.")
    parser.add_argument(
        "--csv",
        type=Path,
        default=REPO_ROOT / "data" / "raw" / "rehab24-6" / "Segmentation.csv",
    )
    parser.add_argument(
        "--splits",
        type=Path,
        default=ML_ROOT / "splits.json",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=REPO_ROOT / "docs" / "split-audit.md",
    )
    args = parser.parse_args(argv)
    report = build_report(args.csv, args.splits)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
